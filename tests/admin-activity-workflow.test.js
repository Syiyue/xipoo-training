assert(admin.includes("if (!C.httpTriggerUrl) throw new Error('HTTP 触发器未配置')"), 'poster recognition does not call an unconfigured HTTP path')
assert(admin.includes("console.error('活动方主页渲染失败', e)"), 'publisher page render errors are recovered')
assert(admin.includes('(Array.isArray(activityList) ? activityList : []).filter'), 'publisher page tolerates missing activity data')
assert(admin.includes("if (!page.innerHTML.trim())"), 'publisher page switches only after successful rendering')
