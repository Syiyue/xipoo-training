assert(admin.includes('AI 修改内容'), 'side assistant is labeled as content modification')
assert(admin.includes("callAdminHttp('aiReviseActivityDraft', payload)"), 'side assistant revises the current draft')

assert(!admin.includes('actPopupContent'), 'admin popup fields are removed')
assert(!activityJs.includes('popupVisible'), 'activity click no longer opens the legacy popup')
assert(!activityWxml.includes('act-popup'), 'legacy popup markup is removed')
assert(adminCloud.includes("popupContentZh: ''"), 'saving an activity clears legacy popup content')
assert(adminCloud.includes('function normalizeAiDraft'), 'AI drafts are normalized before entering the form')
assert(adminCloud.includes('for (let attempt = 0; attempt < 2; attempt++)'), 'text AI retries transient failures once')
assert(adminCloud.includes('return ok({ draft: normalizeAiDraft(draft) })'), 'poster recognition output is normalized')
assert(adminCloud.includes('callDoubaoVision'), 'poster recognition supports Doubao vision')
assert(adminCloud.includes("process.env.ARK_API_KEY"), 'Doubao key is read from environment only')
assert(admin.includes('enabledPublisherKeys'), 'frontend preview filters disabled publishers like the mini program')
