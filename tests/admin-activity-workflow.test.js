const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const admin = fs.readFileSync(path.join(root, 'admin', 'web', 'index.html'), 'utf8')
const activityJs = fs.readFileSync(path.join(root, 'pages', 'activities', 'activities.js'), 'utf8')
const activityWxml = fs.readFileSync(path.join(root, 'pages', 'activities', 'activities.wxml'), 'utf8')
